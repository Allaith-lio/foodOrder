// --- Helpers ---
export const getRestaurantById = (id) =>
  restaurants.find((r) => r.id === id);

export const getRestaurantBySlug = (slug) =>
  restaurants.find((r) => r.slug === slug);

const FEATURED_RESTAURANT_IDS = [3, 8, 10, 11, 12, 13, 14, 15];
export const getFeaturedRestaurants = () =>
  restaurants.filter((r) => FEATURED_RESTAURANT_IDS.includes(r.id));

export const getDishesByRestaurant = (restaurantId) =>
  dishes.filter((d) => d.restaurantId === restaurantId);

export const getFeaturedDishes = (restaurantId) =>
  dishes.filter((d) => d.restaurantId === restaurantId && d.featured);

export const getPopularDishes = () => dishes.filter((d) => d.popular);

export const getMenuCategories = (restaurantId) => {
  const list = getDishesByRestaurant(restaurantId);
  const categories = [];
  list.forEach((dish) => {
    const name = dish.category || "Menu";
    let cat = categories.find((c) => c.id === name.toLowerCase().replace(/\s+/g, "-"));
    if (!cat) {
      cat = { id: name.toLowerCase().replace(/\s+/g, "-"), name, items: [] };
      categories.push(cat);
    }
    cat.items.push(dish);
  });
  return categories;
};

// Build a cart-ready item from a unified dish so cart/wishlist stay consistent.
export const toCartItem = (dish) => ({
  id: dish.id,
  name: dish.name,
  price: dish.price,
  image: dish.image,
  restaurant: dish.restaurant,
});
